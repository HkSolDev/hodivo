export const WORDS_PER_SESSION = 50;

// Server and first client render use this fixed passage; real random words are
// drawn only after hydration so prerendered HTML stays deterministic.
export const INITIAL_WORDS_PASSAGE = COMMON_WORDS.slice(
  0,
  WORDS_PER_SESSION,
).join(' ');

export function getRandomWords(
  count: number = WORDS_PER_SESSION,
  random: () => number = Math.random,
): string {
  const chosen: string[] = [];
  for (let index = 0; index < count; index++) {
    const wordIndex = Math.floor(random() * COMMON_WORDS.length);
    chosen.push(COMMON_WORDS[wordIndex]);
  }
  return chosen.join(' ');
}
